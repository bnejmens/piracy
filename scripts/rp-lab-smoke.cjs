const assert = require('node:assert/strict')
const { chromium } = require('playwright')

;(async () => {
  const browser = await chromium.launch({})
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(process.env.LAB_URL || 'http://127.0.0.1:3417/lab-rp', { timeout: 90000 })
    const editor = page.locator('.tiptap')
    await editor.waitFor({ timeout: 90000 })
    assert.equal(await editor.locator('strong').textContent(), 'Ysill')
    assert.match(await editor.locator('span[style]').getAttribute('style'), /rgb\(183, 141, 230\)|#b78de6/)
    assert.equal(await editor.locator('blockquote').textContent(), 'Quelqu’un est passé avant nous.')
    assert.match(await editor.locator('iframe').getAttribute('src'), /youtube-nocookie\.com\/embed\/aqz-KE-bpKQ/)
    await editor.click()
    await page.keyboard.press('End')
    await page.keyboard.type(' Test.')
    assert.match(await editor.textContent(), /Test/)
    await page.getByRole('button', { name: 'Annuler', exact: true }).click()
    assert.doesNotMatch(await editor.textContent(), /Test/)
    await page.getByRole('button', { name: 'Lancer les dés' }).click()
    const roll = await page.locator('ol li').textContent()
    assert.match(roll, /1d20\+3/)
    const total = Number(roll.split('=').at(-1))
    assert.ok(total >= 4 && total <= 23, roll)
    await page.getByRole('textbox', { name: 'Formule' }).fill('999d20')
    await page.getByRole('button', { name: 'Lancer les dés' }).click()
    assert.match(await page.getByRole('alert').textContent(), /formule/)
    console.log('Tiptap and dice passed')

    await page.getByRole('button', { name: 'Enquête interactive' }).click()
    await page.getByRole('button', { name: 'Examiner le registre' }).click()
    await page.getByText(/tache de cire/).waitFor()
    await page.reload()
    await page.getByRole('button', { name: 'Enquête interactive' }).click()
    await page.getByText(/tache de cire/).waitFor()
    await page.getByRole('button', { name: 'Recommencer' }).click()
    await page.getByRole('button', { name: 'Interroger Mara' }).click()
    await page.getByText(/a emprunté la clé/).waitFor()
    console.log('Ink choices, resume and restart passed')

    await page.getByRole('button', { name: 'Relations', exact: true }).click()
    await page.locator('.react-flow__node').getByText('Mara Vale').click()
    await page.getByText('Archiviste. Elle détient le registre des accès.').waitFor()
    console.log('React Flow selection passed')

    await page.getByRole('button', { name: 'Tableau d’enquête' }).click()
    await page.locator('.excalidraw canvas').first().waitFor({ timeout: 60000 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    assert.deepEqual(errors, [])
    console.log('Excalidraw, mobile layout and browser errors passed')
  } finally {
    await browser.close()
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
